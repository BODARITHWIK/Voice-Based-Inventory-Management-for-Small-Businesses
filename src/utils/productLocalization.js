/**
 * Returns localized date string (e.g. "Today, 02:45 PM" -> "இன்று, 02:45 PM")
 */
export const getLocalizedDateString = (dateStr, langCode) => {
  if (!dateStr || !langCode || langCode === 'en') return dateStr;
  const clean = String(langCode).split('-')[0].toLowerCase();
  let result = String(dateStr);

  for (const [key, mapping] of Object.entries(RELATIVE_DATES)) {
    const regex = new RegExp(`\\b${key}\\b`, 'i');
    if (regex.test(result) && mapping[clean]) {
      result = result.replace(regex, mapping[clean]);
    }
  }

  return result;
};

