  if (SECTION_TRANSLATIONS[lang]) {
    for (const [sec, keys] of Object.entries(SECTION_TRANSLATIONS[lang])) {
      imported[sec] = {
        ...(imported[sec] || {}),
        ...keys
      };
    }
  }

